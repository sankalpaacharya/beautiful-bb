// Generates working-spinner.css: Armada's 4x4 shade grid, a bright diagonal
// front sweeping from the top-left corner in 110ms steps, in place of bb's
// "Working..." shimmer. bb's markup can't gain sixteen cell elements from CSS,
// so one pseudo-element draws them: its background is the top-left cell (a
// box-shadow is not painted under its own box) and box-shadows are the rest.
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const SIZE = 4;
const CELL = 2; // px
const GAP = 1;
const STEP_MS = 110;
const FRONT = [1, 0.75, 0.5];
const TRACK = 0.22;
// Fronts from just before the top-left corner to just past the bottom-right.
const FRAMES = 2 * (SIZE - 1) + 5;

const cells = (front) =>
  Array.from({ length: SIZE * SIZE }, (_, index) => {
    const row = Math.floor(index / SIZE);
    const column = index % SIZE;
    return {
      x: column * (CELL + GAP),
      y: row * (CELL + GAP),
      opacity: FRONT[Math.abs(row + column - front)] ?? TRACK,
    };
  });

const tone = (opacity) =>
  `color-mix(in oklch, var(--bbb-wave) ${Math.round(opacity * 100)}%, transparent)`;

function paint(front, indent) {
  const [corner, ...rest] = cells(front);
  const shadows = rest
    .map(({ x, y, opacity }) => `${x}px ${y}px 0 0 ${tone(opacity)}`)
    .join(`,\n${indent}  `);
  return `${indent}background-color: ${tone(corner.opacity)};\n${indent}box-shadow:\n${indent}  ${shadows};`;
}

const frames = Array.from({ length: FRAMES }, (_, frame) => {
  const at = ((frame / FRAMES) * 100).toFixed(2);
  return `  ${at}% {\n${paint(frame - 2, "    ")}\n  }`;
}).join("\n");

const span = SIZE * CELL + (SIZE - 1) * GAP;
const css = `/* Generated by scripts/build-wave-spinner.mjs; edit that, not this file.
   Replaces the shimmer on bb's "Working..." line with a 4x4 shade grid,
   active while the Wave spinner setting sets <html data-bbb-wave>. */

html[data-bbb-wave] .min-h-7.mt-4 > .animate-shine {
  --bbb-wave: var(--bbb-accent, var(--primary));
  display: inline-flex;
  align-items: center;
  gap: 0.5rem;
  -webkit-text-fill-color: var(--muted-foreground);
  -webkit-mask-image: none;
  mask-image: none;
}
html[data-bbb-wave] .min-h-7.mt-4 > .animate-shine::before {
  content: "";
  flex-shrink: 0;
  width: ${CELL}px;
  height: ${CELL}px;
  margin-right: ${span - CELL}px;
  margin-bottom: ${span - CELL}px;
  animation: bbb-wave ${(FRAMES * STEP_MS) / 1000}s step-end infinite;
}

@keyframes bbb-wave {
${frames}
  100% {
${paint(-2, "    ")}
  }
}

@media (prefers-reduced-motion: reduce) {
  html[data-bbb-wave] .min-h-7.mt-4 > .animate-shine::before {
    animation: none;
${paint(SIZE - 1, "    ")}
  }
}
`;

writeFileSync(join(import.meta.dirname, "..", "working-spinner.css"), css);
console.log(`working-spinner.css: ${Buffer.byteLength(css)} bytes`);
