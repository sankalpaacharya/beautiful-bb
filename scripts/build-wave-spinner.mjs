// Generates working-spinner.css: a 3x3 wave spinner (after heygaia's
// WaveSpinner: diagonal-from-top-left delays, 0.7s pulse) that replaces bb's
// "Working..." shimmer. bb's markup can't gain nine dot elements from CSS, so
// one pseudo-element draws all nine as box-shadows and the keyframes animate
// each shadow's opacity and size with its own delay.
import { writeFileSync } from "node:fs";
import { join } from "node:path";

const DOT = 4; // px, the "sm" size
const GAP = 1.5;
const DURATION = 0.7; // s
const DELAYS = [0, 0.12, 0.24, 0.12, 0.24, 0.36, 0.24, 0.36, 0.48]; // diagonalTL
const STEPS = 28;

// waveSpinnerPulse: opacity 0.3 -> 1 -> 0.3 and scale 0.8 -> 1 -> 0.8.
const pulse = (phase) => 0.5 - 0.5 * Math.cos(2 * Math.PI * phase);

function shadows(t) {
  return DELAYS.map((delay, i) => {
    const p = pulse((((t - delay / DURATION) % 1) + 1) % 1);
    const x = (i % 3) * (DOT + GAP);
    const y = Math.floor(i / 3) * (DOT + GAP);
    const spread = (-(1 - p) * 0.2 * DOT) / 2;
    const alpha = Math.round((0.3 + 0.7 * p) * 100);
    return `${x}px ${y}px 0 ${spread.toFixed(2)}px color-mix(in oklch, var(--bbb-wave) ${alpha}%, transparent)`;
  }).join(", ");
}

const frames = Array.from({ length: STEPS + 1 }, (_, s) => {
  const t = s / STEPS;
  return `  ${(t * 100).toFixed(2)}% {\n    box-shadow: ${shadows(t)};\n  }`;
}).join("\n");

const size = 3 * DOT + 2 * GAP;
const css = `/* Generated by scripts/build-wave-spinner.mjs; edit that, not this file.
   Replaces the shimmer on bb's "Working..." line with a 3x3 wave spinner. */

.min-h-7.mt-4 > .animate-shine {
  --bbb-wave: oklch(0.55 0.17 295);
  display: inline-flex;
  align-items: center;
  gap: 0.5rem;
  -webkit-text-fill-color: var(--muted-foreground);
  -webkit-mask-image: none;
  mask-image: none;
}
.dark .min-h-7.mt-4 > .animate-shine {
  --bbb-wave: oklch(0.78 0.11 295);
}

.min-h-7.mt-4 > .animate-shine::before {
  content: "";
  flex-shrink: 0;
  width: ${DOT}px;
  height: ${DOT}px;
  margin-right: ${size - DOT}px;
  margin-bottom: ${size - DOT}px;
  border-radius: 1px;
  animation: bbb-wave ${DURATION}s linear infinite;
}

@keyframes bbb-wave {
${frames}
}

@media (prefers-reduced-motion: reduce) {
  .min-h-7.mt-4 > .animate-shine::before {
    animation: none;
    box-shadow: ${shadows(0.25)};
  }
}
`;

writeFileSync(join(import.meta.dirname, "..", "working-spinner.css"), css);
console.log(`working-spinner.css: ${Buffer.byteLength(css)} bytes`);
